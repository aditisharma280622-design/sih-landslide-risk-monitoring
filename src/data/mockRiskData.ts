/**
 * The impact-weighted priority score. This is the project's core
 * differentiator: a zone with a lower raw risk probability can still
 * outrank a higher-risk zone if far more people or more critical
 * infrastructure sit in its path.
 *
 * The actual weighting formula lives in `utils/riskSimulation.ts` — the
 * same `calculatePriority()` the live simulation panel uses — so the
 * static dashboard and the simulation can never drift apart.
 */
export function prioritizeZones(zones: RiskZone[]): PrioritizedRiskZone[] {
  const maxPopulation = Math.max(...zones.map((zone) => zone.populationExposed), 1)

  return zones
    .map((zone) => ({
      ...zone,
      ...calculatePriority(zone, maxPopulation),
    }))
    .sort((a, b) => b.priorityScore - a.priorityScore)
}
